"""Human-validation analysis, and a synthetic-annotator simulator.

Two things live here:

``analyze_annotations``
    The analysis the protocol asks for: inter-rater agreement, agreement by
    stratum, human-vs-model AUROC/AUPRC, calibration by score band, action
    disagreement and the false-block rate.

``simulate_annotations``
    A *synthetic crowd*.  The simulated annotators are deliberately built on
    a different, much simpler mechanism than PHC-X -- surface lexical checks
    plus per-annotator noise -- so that the human-vs-model comparison is not
    circular.  Their output is a **dry run**: it proves the analysis pipeline
    works and shows how much label noise the design tolerates before a
    single real person has looked at a single item.

Nothing produced here is human validation.  The simulator is a rehearsal, and
every artifact it writes says so.
"""
from __future__ import annotations

import math
import random
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np

#: The five rubric questions, in the order the protocol lists them.
RUBRIC_QUESTIONS = (
    "supported_by_context",      # yes / no / uncertain
    "contradicts_history",       # yes / no / uncertain
    "presupposition_or_drift",   # yes / no / uncertain
    "would_allow_generation",    # allow / retrieve / clarify / abstain
    "confidence",                # 1-5
)

YES_NO_UNCERTAIN = ("yes", "no", "uncertain")
ACTIONS = ("allow", "retrieve", "clarify", "abstain")

#: how the annotator's answer maps onto the system's action group
HUMAN_TO_GROUP = {
    "allow": "GENERATE",
    "retrieve": "RETRIEVE",
    "clarify": "CLARIFY_OR_ABSTAIN",
    "abstain": "CLARIFY_OR_ABSTAIN",
}

_SIMULATED_WARNING = (
    "SYNTHETIC ANNOTATIONS -- generated by a simulator, not by people. "
    "This is a dry run of the analysis pipeline and must never be reported "
    "as human validation."
)


# --------------------------------------------------------------------- utils
def _content_tokens(text: str) -> List[str]:
    from ..utils.text import content_tokens
    return content_tokens(text or "")


def _lexical_support(answer: str, context: str) -> float:
    """Fraction of the answer's content tokens that appear in the context."""
    a = set(_content_tokens(answer))
    if not a:
        return 0.0
    c = set(_content_tokens(context))
    return len(a & c) / len(a)


def _numeric_conflict(answer: str, context: str) -> bool:
    """Does the answer state a number that the context states differently?"""
    from ..utils.text import tokenize
    import re

    num = re.compile(r"^\d[\d,]*\.?\d*%?$")
    a_nums = {t for t in tokenize(answer) if num.match(t)}
    if not a_nums:
        return False
    c_nums = {t for t in tokenize(context) if num.match(t)}
    return bool(a_nums - c_nums)


_PRESUPPOSITION_CUES = (
    "isn't it true", "is it true", "don't you think", "wasn't it", "aren't you",
    "why did", "how did", "improved from", "increased from", "decreased from",
    "the best", "the worst", "the only", "again", "still",
)


def _has_presupposition_cue(prompt: str) -> bool:
    low = (prompt or "").lower()
    return any(cue in low for cue in _PRESUPPOSITION_CUES)


# ------------------------------------------------------------- krippendorff
def krippendorff_alpha(
    ratings: Dict[Any, Sequence[float]],
    level_of_measurement: str = "ordinal",
) -> Optional[float]:
    """Krippendorff's alpha for (possibly missing) ratings.

    ``ratings`` maps a unit to the list of values it received.  Ordinal
    differences are used, which is what the protocol asks for.
    """
    usable: Dict[Any, List[float]] = {
        unit: [v for v in vals if v is not None]
        for unit, vals in ratings.items()
    }
    usable = {u: v for u, v in usable.items() if len(v) >= 2}
    if not usable:
        return None

    values = sorted({v for vals in usable.values() for v in vals})
    index = {v: i for i, v in enumerate(values)}
    n_values = len(values)

    # coincidence matrix
    coincidence = np.zeros((n_values, n_values), dtype=float)
    for vals in usable.values():
        m = len(vals)
        counts = np.zeros(n_values, dtype=float)
        for v in vals:
            counts[index[v]] += 1
        for c in range(n_values):
            if counts[c] == 0:
                continue
            for k in range(n_values):
                if counts[k] == 0:
                    continue
                if c == k:
                    coincidence[c, k] += counts[c] * (counts[c] - 1) / (m - 1)
                else:
                    coincidence[c, k] += counts[c] * counts[k] / (m - 1)

    marginals = coincidence.sum(axis=1)
    total = marginals.sum()
    if total <= 1:
        return None

    if level_of_measurement == "ordinal":
        delta = np.zeros((n_values, n_values), dtype=float)
        for c in range(n_values):
            for k in range(c, n_values):
                s = marginals[c:k + 1].sum() - (marginals[c] + marginals[k]) / 2.0
                delta[c, k] = delta[k, c] = s * s
    else:  # nominal
        delta = np.ones((n_values, n_values), dtype=float)
        np.fill_diagonal(delta, 0.0)

    d_obs = float((coincidence * delta).sum() / total)
    d_exp = float((np.outer(marginals, marginals) * delta).sum() / (total * (total - 1)))
    if d_exp == 0:
        return None
    return 1.0 - d_obs / d_exp


def fleiss_kappa(labels_by_item: Dict[Any, Sequence[int]], n_categories: int) -> Optional[float]:
    """Fleiss' kappa for items rated by (possibly different) raters."""
    usable = [v for v in labels_by_item.values() if len(v) >= 2]
    if not usable:
        return None
    counts = np.zeros((len(usable), n_categories), dtype=float)
    for i, vals in enumerate(usable):
        for v in vals:
            counts[i, int(v)] += 1
    ratings = counts.sum(axis=1)
    if (ratings == 0).any():
        return None
    p_j = counts.sum(axis=0) / ratings.sum()
    p_i = (np.sum(counts * (counts - 1), axis=1) / (ratings * (ratings - 1))).mean()
    p_e = float((p_j * p_j).sum())
    if p_e == 1.0:
        return None
    return float((p_i - p_e) / (1.0 - p_e))


# ------------------------------------------------------------------ simulate
def simulate_annotations(
    packet: Sequence[Dict[str, Any]],
    key: Sequence[Dict[str, Any]],
    n_annotators: int = 100,
    n_annotations: int = 1000,
    seed: int = 42,
) -> List[Dict[str, Any]]:
    """Produce ``n_annotations`` synthetic annotations over ``packet``.

    Each simulated annotator has a stable personality: how strict they are
    about support, how cautious they are about allowing generation, how often
    they slip, and how well their stated confidence tracks their accuracy.
    Every annotator is blind to the gold label -- they only see the prompt,
    history, evidence and the proposed answer, and they judge it with
    surface lexical checks.
    """
    rng = random.Random(seed)
    by_id = {k["annotation_id"]: k for k in key}
    items = [p for p in packet if p.get("annotation_id") in by_id]
    if not items:
        return []

    annotators: List[Dict[str, Any]] = []
    for a in range(n_annotators):
        annotators.append({
            "code": f"S{rng.randrange(1000, 9999)}",
            # 0 = lenient (answers "yes" easily), 1 = strict
            "strictness": rng.betavariate(2.0, 2.0),
            # 0 = happy to generate, 1 = wants retrieval/clarification
            "caution": rng.betavariate(2.0, 2.0),
            # probability of a slip on any single question
            "slip": rng.uniform(0.02, 0.12),
            # how the stated confidence is biased (positive = overconfident)
            "confidence_bias": rng.uniform(-0.6, 0.6),
            # some annotators are more careful and get more right
            "diligence": rng.uniform(0.55, 0.95),
        })

    # assign work: every item gets several independent labels so that
    # inter-rater agreement is computable
    assignment: List[Tuple[int, int]] = []
    if n_annotations < len(items):
        chosen = rng.sample(range(len(items)), n_annotations)
        for i in chosen:
            assignment.append((i, rng.randrange(n_annotators)))
    else:
        per_item = max(2, n_annotations // max(len(items), 1))
        for i in range(len(items)):
            for _ in range(per_item):
                assignment.append((i, rng.randrange(n_annotators)))
        while len(assignment) < n_annotations:
            assignment.append((rng.randrange(len(items)), rng.randrange(n_annotators)))

    out: List[Dict[str, Any]] = []
    for n, (item_idx, annot_idx) in enumerate(assignment):
        item = items[item_idx]
        annot = annotators[annot_idx]
        answers = _simulate_one(item, annot, rng)
        out.append({
            "annotation_id": item["annotation_id"],
            "annotator_code": annot["code"],
            "round": 0,
            **{q: answers[q] for q in RUBRIC_QUESTIONS},
            "rationale": answers["rationale"],
            "synthetic": True,
        })
    return out


def _simulate_one(item: Dict[str, Any], annot: Dict[str, Any],
                   rng: random.Random) -> Dict[str, Any]:
    """One annotator's judgement of one item, from the visible content only."""
    prompt = str(item.get("prompt", ""))
    history = item.get("conversation_history", []) or []
    evidence = item.get("evidence", []) or []
    answer = str(item.get("proposed_answer", ""))

    hist_text = " ".join(str(h.get("content", "")) for h in history)
    ev_text = " ".join(
        str(e.get("text", e) if isinstance(e, dict) else e) for e in evidence
    )
    context = f"{hist_text} {ev_text}".strip()

    support = _lexical_support(answer, context) if (context or answer) else 0.0
    strict = annot["strictness"]
    slip = annot["slip"]

    # -- Q1: is the answer supported by the supplied context?
    if not context:
        base1 = "uncertain"
    elif support >= 0.65:
        base1 = "yes"
    elif support <= 0.2:
        base1 = "no"
    else:
        base1 = "uncertain"
    # a strict annotator turns marginal "yes" into "uncertain" and
    # "uncertain" into "no"
    if strict > 0.55 and base1 == "yes":
        base1 = "uncertain"
    if strict > 0.7 and base1 == "uncertain":
        base1 = "no"
    if strict < 0.35 and base1 == "uncertain":
        base1 = "yes"
    q1 = _flip(base1, YES_NO_UNCERTAIN, slip, rng)

    # -- Q2: does it contradict the conversation history?
    base2 = "yes" if (hist_text and _numeric_conflict(answer, hist_text)) else "no"
    q2 = _flip(base2, YES_NO_UNCERTAIN, slip, rng)

    # -- Q3: unsupported presupposition or entity/time drift?
    drift = _has_presupposition_cue(prompt) and support < 0.5
    base3 = "yes" if drift else "no"
    if strict < 0.3 and drift:
        base3 = "uncertain"
    q3 = _flip(base3, YES_NO_UNCERTAIN, slip, rng)

    # -- Q4: would you allow generation without retrieval or clarification?
    caution = annot["caution"]
    if q1 == "no" and q2 == "yes":
        base4 = "abstain"
    elif q1 == "no" or q2 == "yes" or q3 == "yes":
        base4 = "clarify" if caution > 0.5 else "retrieve"
    elif q1 == "uncertain":
        base4 = "retrieve" if caution > 0.35 else "allow"
    else:
        base4 = "allow"
    if caution > 0.8 and base4 == "allow":
        base4 = "retrieve"
    if caution < 0.2 and base4 in ("clarify", "abstain"):
        base4 = "retrieve"
    q4 = _flip(base4, ACTIONS, slip * 0.6, rng)

    # -- Q5: confidence and rationale
    definiteness = {"yes": 1.0, "uncertain": 0.5, "no": 1.0}.get(q1, 0.5)
    raw_conf = 2.0 + 2.6 * definiteness + rng.gauss(0, 0.7)
    conf = int(max(1, min(5, round(raw_conf + annot["confidence_bias"]))))
    rationale = _rationale(q1, q2, q3, q4, support)

    return {
        "supported_by_context": q1,
        "contradicts_history": q2,
        "presupposition_or_drift": q3,
        "would_allow_generation": q4,
        "confidence": conf,
        "rationale": rationale,
    }


def _flip(base: str, options: Sequence[str], slip: float,
          rng: random.Random) -> str:
    if rng.random() < slip:
        alternatives = [o for o in options if o != base]
        return rng.choice(alternatives) if alternatives else base
    return base


def _rationale(q1: str, q2: str, q3: str, q4: str, support: float) -> str:
    bits = []
    if q1 == "yes":
        bits.append("the answer is supported by the supplied context")
    elif q1 == "no":
        bits.append("the answer is not supported by the supplied context")
    else:
        bits.append("the supplied context does not settle the question")
    if q2 == "yes":
        bits.append("it conflicts with an earlier turn")
    if q3 == "yes":
        bits.append("it presupposes something the context does not establish")
    bits.append(f"so the right call is to {q4}")
    return "; ".join(bits) + "."


# ------------------------------------------------------------------ analyse
def _group_label(key_row: Dict[str, Any]) -> str:
    """The fine-grained group an item belongs to.

    For DiaHalu this is the annotated error type (non-factual, Reasoning
    Error, ...), because that is what determines whether a support-based
    rubric can reach the item at all.
    """
    errors = key_row.get("error_types") or []
    if errors:
        return "error:" + ",".join(sorted(errors))
    return str(key_row.get("category_or_domain") or "unknown")


def analyze_annotations(
    annotations: Sequence[Dict[str, Any]],
    key: Sequence[Dict[str, Any]],
    seed: int = 42,
) -> Dict[str, Any]:
    """Run the protocol's analysis over a set of annotations.

    Works for real annotations and for the simulated ones; the caller is
    responsible for labelling which it is.
    """
    from ..experiments.metrics import auprc, auroc

    by_id: Dict[str, Dict[str, Any]] = {}
    for a in annotations:
        by_id.setdefault(a["annotation_id"], []).append(a)
    key_by_id = {k["annotation_id"]: k for k in key}

    out: Dict[str, Any] = {
        "n_annotations": len(annotations),
        "n_items": len(by_id),
        "n_annotators": len({a.get("annotator_code") for a in annotations}),
        "warning": _SIMULATED_WARNING,
    }

    # ---- inter-rater agreement -----------------------------------------
    agreement: Dict[str, Any] = {}
    for question, values in (
        ("supported_by_context", ("yes", "no", "uncertain")),
        ("contradicts_history", ("yes", "no", "uncertain")),
        ("presupposition_or_drift", ("yes", "no", "uncertain")),
        ("would_allow_generation", ("allow", "retrieve", "clarify", "abstain")),
    ):
        ratings = {
            item: [a.get(question) for a in rows if a.get(question) is not None]
            for item, rows in by_id.items()
        }
        alpha = krippendorff_alpha(ratings, "ordinal")
        encoded = {
            item: [values.index(v) for v in vals if v in values]
            for item, vals in ratings.items()
        }
        kappa = fleiss_kappa(encoded, len(values))
        agreement[question] = {
            "krippendorff_alpha": round(alpha, 5) if alpha is not None else None,
            "fleiss_kappa": round(kappa, 5) if kappa is not None else None,
        }
    conf_ratings = {
        item: [a.get("confidence") for a in rows if a.get("confidence") is not None]
        for item, rows in by_id.items()
    }
    alpha_conf = krippendorff_alpha(conf_ratings, "ordinal")
    agreement["confidence"] = {
        "krippendorff_alpha": round(alpha_conf, 5) if alpha_conf is not None else None,
    }
    out["agreement"] = agreement

    # ---- how good are the annotators, judged against the gold label? ---
    # For real annotations this is the annotation accuracy; for the simulated
    # crowd it reports the noise level that was injected.
    gold = {
        k["annotation_id"]: k.get("gold_label")
        for k in key if k.get("gold_label") is not None
    }
    if gold:
        correct = total = 0
        by_group: Dict[str, List[int]] = {}
        for a in annotations:
            g = gold.get(a.get("annotation_id"))
            if g is None or a.get("supported_by_context") not in ("yes", "no"):
                continue
            predicted = 1 if a["supported_by_context"] == "no" else 0
            total += 1
            hit = int(predicted == int(g))
            correct += hit
            k = key_by_id.get(a.get("annotation_id"), {})
            group = _group_label(k)
            by_group.setdefault(group, []).append(hit)
        out["annotation_accuracy_vs_gold"] = {
            "n": total,
            "accuracy": round(correct / total, 5) if total else None,
        }
        # Which error types can the rubric actually reach?  This is the
        # diagnostic that matters: a rubric that only asks "is the answer
        # supported by the context?" cannot recover a reasoning error whose
        # facts are all present, so the gold label and the consensus label
        # disagree by construction on those items.
        out["annotation_accuracy_by_group"] = {
            group: {
                "n": len(hits),
                "accuracy": round(float(np.mean(hits)), 5),
            }
            for group, hits in sorted(by_group.items())
        }
        # Which error types can the rubric reach at all?  A rubric that only
        # asks "is the answer supported by the context?" cannot recover a
        # *reasoning* error whose facts are all present: the answer really is
        # supported, so the consensus label and the gold label disagree by
        # construction.  That is a protocol defect, not annotator noise.
        reachable: List[int] = []
        unreachable: List[int] = []
        for group, hits in by_group.items():
            if group.startswith("error:"):
                kinds = {k.strip().lower() for k in group.split(":", 1)[1].split(",")}
                if kinds & {"reasoning error"}:
                    unreachable.extend(hits)
                else:
                    reachable.extend(hits)
        if reachable or unreachable:
            out["rubric_reachability"] = {
                "fact_and_context_errors": {
                    "n": len(reachable),
                    "accuracy": round(float(np.mean(reachable)), 5) if reachable else None,
                },
                "reasoning_errors": {
                    "n": len(unreachable),
                    "accuracy": round(float(np.mean(unreachable)), 5) if unreachable else None,
                },
                "note": (
                    "the support-based rubric cannot reach reasoning errors: the "
                    "answer's facts are present, so a literal 'yes' is the correct "
                    "answer to the question and still disagrees with the gold label"
                ),
            }

    # ---- per-item consensus label --------------------------------------
    # the consensus "hallucination" label is the majority answer to Q1:
    # an answer the annotators judge unsupported is a hallucination
    consensus: Dict[str, int] = {}
    consensus_action: Dict[str, str] = {}
    for item, rows in by_id.items():
        answers = [a.get("supported_by_context") for a in rows]
        answers = [a for a in answers if a in ("yes", "no")]
        if not answers:
            continue
        n_no = sum(1 for a in answers if a == "no")
        n_yes = sum(1 for a in answers if a == "yes")
        consensus[item] = 1 if n_no > n_yes else 0
        acts = [a.get("would_allow_generation") for a in rows
                if a.get("would_allow_generation") in HUMAN_TO_GROUP]
        if acts:
            consensus_action[item] = max(set(acts), key=acts.count)

    # ---- human vs model -------------------------------------------------
    items = [i for i in consensus if i in key_by_id]
    if items:
        y = np.asarray([consensus[i] for i in items], dtype=int)
        scores = np.asarray([float(key_by_id[i].get("risk_score", 0.0)) for i in items])
        out["human_vs_model"] = {
            "n": len(items),
            "human_positive_rate": round(float(y.mean()), 5),
            "auroc": round(float(auroc(y, scores)), 5),
            "auprc": round(float(auprc(y, scores)), 5) if y.sum() else None,
        }

        # calibration by score band
        bands: Dict[str, List[int]] = {}
        for i, label in zip(items, y):
            band = key_by_id[i].get("score_band", "UNKNOWN")
            bands.setdefault(band, []).append(label)
        out["calibration_by_band"] = {
            band: {
                "n": len(labels),
                "human_hallucination_rate": round(float(np.mean(labels)), 5),
                "model_mean_risk": round(float(np.mean([
                    float(key_by_id[i].get("risk_score", 0.0))
                    for i in items if key_by_id[i].get("score_band") == band
                ])), 5),
            }
            for band, labels in sorted(bands.items())
        }

        # agreement by stratum
        by_stratum: Dict[str, List[int]] = {}
        for i, label in zip(items, y):
            by_stratum.setdefault(str(key_by_id[i].get("category_or_domain")), []).append(label)
        out["agreement_by_stratum"] = {
            stratum: {"n": len(labels),
                      "human_hallucination_rate": round(float(np.mean(labels)), 5)}
            for stratum, labels in sorted(by_stratum.items())
        }

        # action disagreement and the false-block rate
        agree = 0
        disagreements: Dict[str, int] = {}
        false_blocks = 0
        blocked_and_human_allows = 0
        retrieved_needed = 0
        retrieved_and_unsupported = 0
        for i in items:
            k = key_by_id[i]
            model_group = k.get("action_group")
            human_group = HUMAN_TO_GROUP.get(consensus_action.get(i, ""))
            if human_group is None or model_group is None:
                continue
            if model_group == human_group:
                agree += 1
            else:
                disagreements[f"{model_group}->{human_group}"] = \
                    disagreements.get(f"{model_group}->{human_group}", 0) + 1
            if model_group == "CLARIFY_OR_ABSTAIN" and human_group == "GENERATE":
                false_blocks += 1
            if model_group == "CLARIFY_OR_ABSTAIN":
                blocked_and_human_allows += 1
            if consensus[i] == 1:
                retrieved_needed += 1
                if human_group in ("RETRIEVE", "CLARIFY_OR_ABSTAIN"):
                    retrieved_and_unsupported += 1
        n_action = sum(1 for i in items
                       if key_by_id[i].get("action_group")
                       and consensus_action.get(i) in HUMAN_TO_GROUP)
        out["action_agreement"] = {
            "n": n_action,
            "agreement": round(agree / n_action, 5) if n_action else None,
            "disagreements": disagreements,
            "false_block_rate": round(false_blocks / blocked_and_human_allows, 5)
            if blocked_and_human_allows else None,
            "retrieval_indicated_among_unsupported": round(
                retrieved_and_unsupported / retrieved_needed, 5) if retrieved_needed else None,
            "note": (
                "the proportion of cases where retrieval was indicated is measured "
                "from the annotators' chosen action, not from regenerating an answer"
            ),
        }

    return out
